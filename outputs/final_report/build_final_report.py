# ---------- doc helpers ----------
def set_run_font(run, size=None, bold=None, color=None, italic=None, font=FONT_CN):
    run.font.name = font
    run._element.rPr.rFonts.set(qn('w:ascii'), FONT_EN)
    run._element.rPr.rFonts.set(qn('w:hAnsi'), FONT_EN)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font)
    if size is not None: run.font.size = Pt(size)
    if bold is not None: run.bold = bold
    if italic is not None: run.italic = italic
    if color is not None: run.font.color.rgb = color

def set_para_format(p, before=0, after=6, line=1.10, align=None):
    pf=p.paragraph_format
    pf.space_before=Pt(before)
    pf.space_after=Pt(after)
    pf.line_spacing=line
    if align is not None: p.alignment=align

def add_p(doc, text='', size=11, bold=False, color=None, align=None, before=0, after=6, line=1.10, italic=False):
    p=doc.add_paragraph()
    set_para_format(p,before,after,line,align)
    r=p.add_run(text)
    set_run_font(r,size=size,bold=bold,color=color,italic=italic)
    return p

def add_heading(doc, text, level=1):
    p=doc.add_paragraph(style=f'Heading {level}')
    p.paragraph_format.keep_with_next=True
    r=p.add_run(text)
    set_run_font(r, size={1:16,2:13,3:12}.get(level,11), bold=True, color=BLUE if level<3 else DARK)
    return p

def set_cell_text(cell, text, bold=False, size=9, align=WD_ALIGN_PARAGRAPH.CENTER, color=None):
    cell.text=''
    p=cell.paragraphs[0]
    p.alignment=align
    p.paragraph_format.space_before=Pt(0)
    p.paragraph_format.space_after=Pt(0)
    p.paragraph_format.line_spacing=1.05
    r=p.add_run(str(text))
    set_run_font(r,size=size,bold=bold,color=color)
    cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER

def shade_cell(cell, fill):
    tcPr=cell._tc.get_or_add_tcPr()
    shd=tcPr.find(qn('w:shd'))
    if shd is None:
        shd=OxmlElement('w:shd')
        tcPr.append(shd)
    shd.set(qn('w:fill'), fill)

def set_cell_margins(cell, top=80, start=120, bottom=80, end=120):
    tc=cell._tc
    tcPr=tc.get_or_add_tcPr()
    tcMar=tcPr.first_child_found_in('w:tcMar')
    if tcMar is None:
        tcMar=OxmlElement('w:tcMar')
        tcPr.append(tcMar)
    for m,v in [('top',top),('start',start),('bottom',bottom),('end',end)]:
        node=tcMar.find(qn(f'w:{m}'))
        if node is None:
            node=OxmlElement(f'w:{m}')
            tcMar.append(node)
        node.set(qn('w:w'), str(v)); node.set(qn('w:type'),'dxa')

def set_table_widths(table, widths):
    table.alignment=WD_TABLE_ALIGNMENT.CENTER
    table.autofit=False
    tbl=table._tbl
    tblPr=tbl.tblPr
    tblW=tblPr.find(qn('w:tblW'))
    if tblW is None:
        tblW=OxmlElement('w:tblW'); tblPr.append(tblW)
    tblW.set(qn('w:w'), str(sum(widths))); tblW.set(qn('w:type'),'dxa')
    tblInd=tblPr.find(qn('w:tblInd'))
    if tblInd is None:
        tblInd=OxmlElement('w:tblInd'); tblPr.append(tblInd)
    tblInd.set(qn('w:w'),'120'); tblInd.set(qn('w:type'),'dxa')
    grid=tbl.tblGrid
    if grid is None:
        grid=OxmlElement('w:tblGrid'); tbl.insert(0, grid)
    for child in list(grid): grid.remove(child)
    for w in widths:
        gc=OxmlElement('w:gridCol'); gc.set(qn('w:w'), str(w)); grid.append(gc)
    for row in table.rows:
        for i,cell in enumerate(row.cells):
            cell.width = Pt(widths[i]/20)
            tcPr=cell._tc.get_or_add_tcPr()
            tcW=tcPr.find(qn('w:tcW'))
            if tcW is None:
                tcW=OxmlElement('w:tcW'); tcPr.append(tcW)
            tcW.set(qn('w:w'), str(widths[i])); tcW.set(qn('w:type'),'dxa')
            set_cell_margins(cell)

def add_table(doc, headers, rows, widths, caption=None, small=False):
    if caption:
        add_p(doc, caption, size=9.5, bold=True, color=MUTED, before=4, after=4)
    table=doc.add_table(rows=1, cols=len(headers))
    table.style='Table Grid'
    set_table_widths(table, widths)
    for i,h in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], h, bold=True, size=8 if small else 9, align=WD_ALIGN_PARAGRAPH.CENTER)
        shade_cell(table.rows[0].cells[i], LIGHT_BLUE)
    for row in rows:
        cells=table.add_row().cells
        for i,val in enumerate(row):
            align=WD_ALIGN_PARAGRAPH.LEFT if isinstance(val,str) and len(val)>18 else WD_ALIGN_PARAGRAPH.CENTER
            set_cell_text(cells[i], val, size=7.6 if small else 8.8, align=align)
    doc.add_paragraph().paragraph_format.space_after=Pt(2)
    return table

def fmt(x):
    if isinstance(x,float): return f'{x:.4f}'
    return str(x)

def add_bullets(doc, items):
    for text in items:
        p=doc.add_paragraph(style='List Bullet')
        p.paragraph_format.space_after=Pt(4)
        p.paragraph_format.line_spacing=1.10
        r=p.add_run(text)
        set_run_font(r,size=10.5)

def add_numbered(doc, items):
    for text in items:
        p=doc.add_paragraph(style='List Number')
        p.paragraph_format.space_after=Pt(4)
        p.paragraph_format.line_spacing=1.10
        r=p.add_run(text)
        set_run_font(r,size=10.5)

def add_image(doc, path, caption, width=6.1):
    p=doc.add_paragraph()
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    run=p.add_run()
    run.add_picture(str(path), width=Inches(width))
    add_p(doc, caption, size=9, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER, before=0, after=8)

